/**
 * Writes the license text of every npm package that esbuild bundled into the server (and any NOTICE file, which
 * Apache-2.0 section 4(d) requires us to pass on) to one file. The packages are found from esbuild's metafile, so
 * the list is exactly what is in `dist/main.mjs`, `dist/index.mjs` and `dist/admin.mjs` (one metafile covers all entries). Packages kept outside the bundle
 * (see EXTERNAL in build.mjs) are installed with their own license files and are not repeated here.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const MARK = 'node_modules/';
const TEXT_FILE = /^(licen[sc]e|licen[sc]es|copying|notice|unlicense)([-._].*)?(\.(md|txt))?$/i;

/** Root folder of the package that owns `file` (an input path from the metafile), or null for our own code. */
function packageRoot(file) {
  const at = file.lastIndexOf(MARK);
  if (at < 0) return null;
  const rest = file.slice(at + MARK.length).split('/');
  const len = rest[0].startsWith('@') ? 2 : 1;
  return file.slice(0, at + MARK.length) + rest.slice(0, len).join('/');
}

export function writeLicenses(metafile, outFile, cwd = process.cwd()) {
  const roots = new Set();
  for (const file of Object.keys(metafile.inputs)) {
    const root = packageRoot(file);
    if (root) roots.add(root);
  }
  const packages = [...roots]
    .map((root) => {
      const dir = resolve(cwd, root);
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      const files = readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isFile() && TEXT_FILE.test(e.name))
        .map((e) => e.name)
        .sort();
      const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'see package');
      return { name: pkg.name, version: pkg.version, license, repository: repoUrl(pkg), dir, files };
    })
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  const missing = packages.filter((p) => !p.files.some((f) => !/^notice/i.test(f)));
  // npm tarballs of some Apache-2.0 packages omit the LICENSE file; the license must still accompany them
  const apacheText = apacheLicenseText(packages);
  const out = [
    'Third-party licenses of the packages bundled into the Critical Notes server.',
    'Generated by apps/server/scripts/licenses.mjs during the build. Do not edit.',
    `Packages: ${packages.length}`,
    '',
  ];
  for (const p of packages) {
    out.push('='.repeat(78), `${p.name}@${p.version}`, `License: ${p.license}`);
    if (p.repository) out.push(`Source: ${p.repository}`);
    out.push('');
    if (!p.files.some((f) => !/^notice/i.test(f))) {
      const standard = p.license === 'Apache-2.0' && apacheText;
      out.push(`(This package ships no license file. It declares the license ${p.license}.${standard ? ' The standard text follows; the copyright holder is named in the package source above.' : ''})`, '');
      if (standard) out.push(apacheText, '');
    }
    for (const f of p.files) {
      out.push(`--- ${f} ---`, readFileSync(join(p.dir, f), 'utf8').trim(), '');
    }
  }
  writeFileSync(outFile, `${out.join('\n')}\n`);
  return { count: packages.length, withoutLicenseFile: missing.map((p) => `${p.name}@${p.version}`) };
}

function repoUrl(pkg) {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return r ? r.replace(/^git\+/, '').replace(/\.git$/, '') : (pkg.homepage ?? '');
}

/** The plain Apache-2.0 text from the first bundled package whose license file is exactly that text. */
function apacheLicenseText(packages) {
  for (const p of packages) {
    if (p.license !== 'Apache-2.0') continue;
    for (const f of p.files) {
      const text = readFileSync(join(p.dir, f), 'utf8').trim();
      if (/^licen[sc]e/i.test(f) && /^Apache License\s+Version 2\.0/.test(text)) return text;
    }
  }
  return '';
}
